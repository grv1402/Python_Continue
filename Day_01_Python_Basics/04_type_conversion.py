# Python provides built-in functions for TypeCasting:
#   int() : Convert to integer
#   float() : Convert to float
#   str() : Convert to string
#   bool() : Convert to boolean

a = 14
b = "14"

print(type(a))
print(type(b))

#  Convert b to an integer

c = int(b)
print(c)
print(type(c))

#  Convert a to string

d = str(a)
print(d)
print(type(d))
