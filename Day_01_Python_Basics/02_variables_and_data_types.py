# Data types

# Python supports several built-in data types:
#     Integers (int): Whole numbers (e.g., 14, -2).
#     Floats (float): Decimal numbers (e.g., 2.14, -0.001).
#     Strings (str): Text data enclosed in quotes (e.g., "Hello", "Python").
#     Booleans (Bool): Represents True or False.
#     Lists: Ordered, mutables collections (e.g., [1, 2, 3]). Change the values.
#     Tuples: Ordered, immutable collections (e.g., (1, 2, 3)). Cannot change the values.
#     Sets: Unordered collections if unique elements (e.g., {1, 2, 3}).
#     Dictionaries: Key-value pairs (e.g., {"name": "Gaurav", "age": 19}).

